#!/bin/zsh
# Build a release: universal (Apple Silicon + Intel) app with an installer,
# written to updates/SkadisModeler.zip + updates/latest.json. Committing and
# pushing updates/ ships it: every installed copy's "Check for Updates" reads
# latest.json from this repo on GitHub.
#
# Bump VERSION, write the notes in RELEASE_NOTES.txt (or pass UPDATE_NOTES),
# then: ./release.sh
# (without UPDATE_NOTES the notes come from RELEASE_NOTES.txt)
set -e
cd "$(dirname "$0")"
VERSION=$(cat VERSION)
REPO="${REPO:-jonpikereally/skadismodeler}"
# Every error code used in the app and installer must be on the public error list.
missing=$(grep -ohE 'SM-[0-9]{3}' Sources/SkadisModeler/*.swift release.sh install.sh | sort -u | while read -r c; do
  grep -q "^| $c |" ERRORS.md || echo "$c"
done)
if [[ -n "$missing" ]]; then
  echo "Error codes missing from ERRORS.md: $missing" >&2
  exit 1
fi
if [[ -z "${UPDATE_NOTES:-}" && -f RELEASE_NOTES.txt ]]; then
  UPDATE_NOTES=$(<RELEASE_NOTES.txt)
fi
BUILT=$(date "+%b %d, %H:%M")
FEED="${UPDATE_FEED-https://raw.githubusercontent.com/$REPO/main/updates/latest.json}"
cat > Sources/SkadisModeler/Version.swift <<SWIFT
// Generated by build.sh / release.sh — do not edit.
enum AppVersion {
    static let version = "$VERSION"
    static let built = "$BUILT"
    static let repo = "$REPO"
    static let updateFeed = "$FEED"
}
SWIFT
CACHE="${TMPDIR:-/tmp}/skadismodeler-modcache"
mkdir -p "$CACHE"
echo "Building arm64…"
swiftc -O -target arm64-apple-macos13 -module-cache-path "$CACHE" \
  -o "$CACHE/SkadisModeler-arm64" Sources/SkadisModeler/*.swift
echo "Building x86_64…"
swiftc -O -target x86_64-apple-macos13 -module-cache-path "$CACHE-x86" \
  -o "$CACHE/SkadisModeler-x86_64" Sources/SkadisModeler/*.swift

DIST="$CACHE/dist"
rm -rf "$DIST"
APP="$DIST/SkadisModeler/SkadisModeler.app"
mkdir -p "$APP/Contents/MacOS"
lipo -create -output "$APP/Contents/MacOS/SkadisModeler" \
  "$CACHE/SkadisModeler-arm64" "$CACHE/SkadisModeler-x86_64"
cp Resources/Info.plist "$APP/Contents/Info.plist"
mkdir -p "$APP/Contents/Resources"
cp Resources/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Contents/Info.plist"
codesign --force --sign - "$APP"

cat > "$DIST/SkadisModeler/Install SkadisModeler.command" <<INSTALL
#!/bin/bash
# SkadisModeler installer — copies the app to ~/Applications and launches it.
cd "\$(dirname "\$0")"
fail() {
  echo
  echo "Error \$1: \$2"
  echo "Look up this code on the SkadisModeler error list:"
  echo "  https://github.com/$REPO/blob/main/ERRORS.md"
  echo "(You can also give that page to an AI assistant for help.)"
  exit 1
}
echo "Installing SkadisModeler…"
mkdir -p ~/Applications || fail SM-601 "Couldn't create ~/Applications."
rm -rf ~/Applications/SkadisModeler.app
ditto --norsrc SkadisModeler.app ~/Applications/SkadisModeler.app \\
  || fail SM-601 "Couldn't copy SkadisModeler into ~/Applications."
# Clear the download quarantine and re-sign locally so macOS trusts it on this Mac.
xattr -dr com.apple.quarantine ~/Applications/SkadisModeler.app 2>/dev/null
codesign --force --sign - ~/Applications/SkadisModeler.app 2>/dev/null \\
  || fail SM-602 "Couldn't sign SkadisModeler for this Mac."
open ~/Applications/SkadisModeler.app \\
  || fail SM-603 "SkadisModeler was installed but couldn't be opened. Open it from ~/Applications yourself."
echo
echo "Done! Click + to add your STL or 3MF models, then drag them around the board."
INSTALL
chmod +x "$DIST/SkadisModeler/Install SkadisModeler.command"

cat > "$DIST/SkadisModeler/README.txt" <<README
SkadisModeler v$VERSION — see how your 3D-printed SKADIS pegboard designs fit before you print them (macOS 13+)
https://github.com/$REPO

INSTALL
1. Double-click "Install SkadisModeler.command".
   If macOS blocks it: right-click it, choose Open, then Open again.

USE
1. Pick your board size on the right.
2. Click + (or drop files on the window) to add STL or 3MF models. Each one is
   hung on the first free slots that fit it.
3. Drag a model to move it from slot to slot. Drag the board to look around,
   scroll to zoom. Anything that overlaps, misses the slots or hangs off the
   board turns red and says why.

PRIVACY
SkadisModeler only reads the model files you add. No accounts, no analytics.
The only thing it fetches from the internet is a small version file from the
GitHub repo above, to see whether an update exists.
README

mkdir -p updates
(cd "$DIST" && ditto -c -k --norsrc --noextattr --noqtn --keepParent SkadisModeler "$OLDPWD/updates/SkadisModeler.zip.tmp")
mv -f updates/SkadisModeler.zip.tmp updates/SkadisModeler.zip
# Manifest last, so a checking app never sees it pointing at a half-written zip.
/usr/bin/python3 -c 'import json,sys; print(json.dumps({"version": sys.argv[1], "url": "SkadisModeler.zip", "notes": sys.argv[2]}))' \
  "$VERSION" "${UPDATE_NOTES:-}" > updates/latest.json.tmp
mv -f updates/latest.json.tmp updates/latest.json

./build.sh >/dev/null
echo "Release v$VERSION written to updates/. Ship it with:"
echo "  git add -A && git commit -m \"Release v$VERSION\" && git push"
